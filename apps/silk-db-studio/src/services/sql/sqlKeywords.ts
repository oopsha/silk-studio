const DRIVER_EXTRAS: Record<ConnectionDriverId, string[]> = {
  oracle: ORACLE_EXTRA,
  sqlserver: TSQL_EXTRA,
  mysql: MYSQL_EXTRA,
  mariadb: MYSQL_EXTRA,
  postgresql: PG_EXTRA,
};

export function keywordsForDriver(driverId: ConnectionDriverId): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const word of [
    ...COMMON_KEYWORDS,
    ...COMMON_FUNCTIONS,
    ...DRIVER_EXTRAS[driverId],
  ]) {
    const key = word.toUpperCase();
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(word);
  }
  return result;
}
